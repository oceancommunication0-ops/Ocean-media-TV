test('Opportunités enregistre une annonce complète et structurée', async ({ page }) => {
  await auth(page)
  await page.route('**/api/admin/categories/opportunities', route => route.fulfill({ json: { items: [{ id: 'emploi', label: 'Emploi', count: 0, sortOrder: 0 }] } }))
  await page.route('**/api/admin/content/opportunities?*', route => route.fulfill({ json: { items: [], pagination: { page: 1, limit: 9, total: 0, totalPages: 0 } } }))
  await page.route('**/api/admin/content/opportunities', route => route.fulfill({ status: 201, json: { data: route.request().postDataJSON().data } }))
  await login(page, '/admin/opportunites')
  await page.getByRole('button', { name: 'Nouvelle opportunité', exact: true }).click()
  const dialog = page.getByRole('dialog', { name: 'Créer une opportunité', exact: true })
  await dialog.getByLabel('Titre de l’opportunité').fill('Chargé de communication jeunesse')
  await dialog.getByLabel('Résumé').fill('Une mission éditoriale au service des projets de jeunesse.')
  await dialog.getByLabel('Organisation').fill('Océan Communication')
  await expect(dialog.getByLabel('Référence')).toHaveCount(0)
  await expect(dialog.getByLabel('Mode', { exact: true })).toHaveCount(0)
  await expect(dialog.getByLabel('Identifiant', { exact: true })).toHaveCount(0)
  await dialog.getByLabel('Format').fill('CDD')
  await dialog.getByLabel('Public concerné').fill('Jeunes diplômés')
  await dialog.getByLabel('À propos de l’opportunité').fill('Une mission complète et accompagnée.')
  await dialog.getByLabel('Ce que l’opportunité propose').fill('Encadrement\nExpérience professionnelle')
  await dialog.getByLabel('Profil recherché').fill('Bonne rédaction\nEsprit d’équipe')
  await dialog.getByLabel('Pièces à préparer').fill('Curriculum vitae')
  await dialog.getByLabel('Étape', { exact: true }).fill('Préparer son dossier')
  await dialog.getByLabel('Explication').fill('Réunir les documents demandés.')
  await dialog.locator('select[name="publication"]').selectOption('published')
  const requestPromise = page.waitForRequest(request => request.method() === 'POST' && request.url().endsWith('/api/admin/content/opportunities'))
  await dialog.getByRole('button', { name: 'Enregistrer', exact: true }).click()
  const payload = (await requestPromise).postDataJSON()
  expect(payload.data.benefits).toEqual(['Encadrement', 'Expérience professionnelle'])
  expect(payload.data.steps).toEqual([{ title: 'Préparer son dossier', description: 'Réunir les documents demandés.' }])
  expect(payload.data.href).toContain('/opportunites/charge-de-communication-jeunesse')
  expect(payload.published).toBe(true)
  expect(payload.data.id).toMatch(/-[a-f0-9]{8}$/)
})

